-- EMPLOYEE
CREATE TABLE IF NOT EXISTS employee (
  empno         VARCHAR(5)   NOT NULL,
  lastname      VARCHAR(15),
  firstname     VARCHAR(15),
  gender        CHAR(1)      CONSTRAINT gender_ck CHECK (gender IN ('M','F')),
  birthdate     DATE,
  hiredate      DATE,
  sepDate       DATE,
  record_status VARCHAR(10)  NOT NULL DEFAULT 'ACTIVE',
  stamp         VARCHAR(60),
  PRIMARY KEY (empno),
  CONSTRAINT emp_status_ck CHECK (record_status IN ('ACTIVE','INACTIVE'))
);

