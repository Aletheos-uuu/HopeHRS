-- DEPARTMENT
CREATE TABLE IF NOT EXISTS department (
  deptCode      VARCHAR(3)   NOT NULL,
  deptName      VARCHAR(20),
  record_status VARCHAR(10)  NOT NULL DEFAULT 'ACTIVE',
  stamp         VARCHAR(60),
  PRIMARY KEY (deptCode),
  CONSTRAINT dept_status_ck CHECK (record_status IN ('ACTIVE','INACTIVE'))
);

